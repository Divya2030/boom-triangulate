PROLOGUE = """\
/* Generated by chia_loop.generate -- do not edit by hand.
 * hypothesis: {hid}
 * category:   {category}
 * provenance: {provenance}
 */
#include "common.S"

  .section .text.init
  .globl _start
_start:
"""


@dataclass
class TestProgram:
    id: str
    hypothesis_id: str
    category: str
    body: str
    needs_trap: bool = False
    provenance: str = "offline-template"
    path: str = ""

    def render(self) -> str:
        head = PROLOGUE.format(hid=self.hypothesis_id, category=self.category,
                               provenance=self.provenance)
        setup = "  TRAP_SETUP\n" if self.needs_trap else ""
        return head + setup + self.body + "  TEST_PASS\n"

    def write(self, directory: str = GENERATED) -> str:
        os.makedirs(directory, exist_ok=True)
        self.path = os.path.join(directory, f"{self.id}.S")
        with open(self.path, "w") as fh:
            fh.write(self.render())
        return self.path


@dataclass
class Validation:
    """Why a program was accepted or rejected. Rejections are not failures of
    the loop; they are the gate doing its job, and the counts are worth
    reporting."""

    ok: bool = False
    assembles: bool = False
    terminates: bool = False
    events: int = 0
    reason: str = ""
    detail: str = field(default="", repr=False)

    def to_dict(self) -> dict:
        return {"ok": self.ok, "assembles": self.assembles,
                "terminates": self.terminates, "events": self.events,
                "reason": self.reason}


def validate(program: TestProgram, min_events: int = 8,
             max_insns: int = 200_000, start_pc: int = 0x80000000) -> Validation:
    """Assemble, run on the oracle, and require real work to have happened."""
    v = Validation()
    if not program.path:
        program.write()

    elf = os.path.join(REPO, "build", "progs", f"{program.id}.elf")
    build = models.build_elf(program.path, elf)
    if not build.ok:
        v.reason = "does not assemble"
        v.detail = build.output[-3000:]
        return v
    v.assembles = True

    res = models.run_spike(elf, max_insns=max_insns)
    events = trace.truncate_at_halt(trace.parse_commit_log(res.output))
    after_sync = [e for n, e in enumerate(events)
                  if any(x.pc == start_pc for x in events[:n + 1])]
    v.events = len(after_sync)

    if not res.ok:
        v.reason = f"oracle exited {res.returncode}"
        v.detail = res.output[-3000:]
        return v
    v.terminates = True

    if v.events < min_events:
        v.reason = (f"retired only {v.events} instructions after sync "
                    f"(minimum {min_events}); a program that does nothing "
                    "produces a clean comparison and proves nothing")
        return v

    v.ok = True
    v.reason = "accepted"
    return v


_PROMPT = """You are writing a bare-metal RISC-V test program to expose a \
disagreement between an out-of-order implementation (BOOM) and ISA reference \
models (Spike, Dromajo) over COMMITTED architectural state.

Hypothesis: {title}
Category: {category}
Rationale: {rationale}
Preconditions: {preconditions}
Intended stimulus: {stimulus}
Expected divergence: {expected}

Write ONLY the instruction sequence for the body of _start.

DESIGN THE TEST SO A DEFECT IS EASY TO SEE AND EASY TO CLASSIFY:
1. Localise the effect. Drive the suspect microarchitectural condition, then
   capture its result into ONE callee-saved register (s2-s11) and leave it
   there. A single wrong register value is an unambiguous divergence; a wrong
   value that flows into a branch or an address derails the whole trace and
   looks like a harness artifact instead of a bug.
2. No data-dependent control flow after the suspect value is produced. Do not
   branch on it, do not use it as a load/store address. Keep control flow
   identical on both machines so the ONLY possible divergence is the captured
   value.
3. Make the two outcomes numerically distinct. Arrange operands so the correct
   result and the buggy result differ in low bits that are obvious in a commit
   log (avoid values that alias to 0).
4. Exercise the seam repeatedly with varied operands (a short .rept or an
   unrolled sequence) to raise the chance of hitting the precondition, but keep
   the program under ~60 instructions and strictly terminating.

CONSTRAINTS:
- RV64GC, GNU as syntax. No prologue, _start label, .section, or exit code.
- Touch only the 256-byte buffer at symbol `scratch`.
- No pseudo-ops needing relaxation other than `la`. `.rept`/`.endr` allowed.
- The program MUST terminate: no unbounded loops, no jumps outside the body.
{trap_note}
Respond as JSON: {{"body": "<assembly>", "needs_trap": true|false, \
"explanation": "<one sentence naming the register that will differ>"}}
"""

TRAP_NOTE = """- A trap handler is installed for you. It records mcause into s2 \
and steps over the faulting instruction, so you may deliberately trap and then \
read s2 to place the cause into committed state.
"""


def _sanitize(body: str) -> str:
    """Strip anything the render path already supplies or that could escape it.

    A generated body that redefines _start or emits its own .section silently
    changes the program's layout, and a tohost write ends the run early.
    """
    out = []
    banned = re.compile(r"^\s*(\.section|\.globl\s+_start|_start\s*:|"
                        r"\.text|\.data|\.bss|#include)", re.I)
    for line in body.splitlines():
        if banned.match(line):
            continue
        if "tohost" in line:
            continue
        out.append(line.rstrip())
    text = "\n".join(out).strip("\n")
    return text + "\n" if text else ""


def synthesize(hypothesis: Hypothesis, agent: Agent | None = None,
               index: int = 1) -> TestProgram:
    agent = agent or Agent()
    pid = f"{hypothesis.category.lower()}_{index}"

    if not agent.online:
        body, needs_trap = TEMPLATES.get(
            hypothesis.category, TEMPLATES["ACKNOWLEDGED_GAP"])
        return TestProgram(pid, hypothesis.id, hypothesis.category, body,
                           needs_trap, "offline-template")

    prompt = _PROMPT.format(
        title=hypothesis.title, category=hypothesis.category,
        rationale=hypothesis.rationale, preconditions=hypothesis.preconditions,
        stimulus=hypothesis.stimulus_sketch,
        expected=hypothesis.expected_divergence,
        trap_note=TRAP_NOTE if hypothesis.category == "EXCEPTION_PRIORITY" else "")
    try:
        raw = agent.complete(prompt)
    except Exception:                                   # noqa: BLE001
        body, needs_trap = TEMPLATES.get(
            hypothesis.category, TEMPLATES["ACKNOWLEDGED_GAP"])
        return TestProgram(pid, hypothesis.id, hypothesis.category, body,
                           needs_trap, "offline-template (model call failed)")

    from .agent import _parse_json
    data = _parse_json(raw)
    body = _sanitize(str(data.get("body", "")))
    if not body:
        body, needs_trap = TEMPLATES.get(
            hypothesis.category, TEMPLATES["ACKNOWLEDGED_GAP"])
        return TestProgram(pid, hypothesis.id, hypothesis.category, body,
                           needs_trap, "offline-template (empty model output)")

    return TestProgram(pid, hypothesis.id, hypothesis.category, body,
                       bool(data.get("needs_trap", False)), agent.provenance)


def generate_suite(hypotheses: list[Hypothesis], agent: Agent | None = None,
                   min_events: int = 8) -> list[tuple[TestProgram, Validation]]:
    agent = agent or Agent()
    seen: dict[str, int] = {}
    out = []
    for h in hypotheses:
        seen[h.category] = seen.get(h.category, 0) + 1
        prog = synthesize(h, agent=agent, index=seen[h.category])
        prog.write()
        out.append((prog, validate(prog, min_events=min_events)))
    return out
