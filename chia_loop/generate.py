"""Generate block: turn a hypothesis into a runnable test program.

A hypothesis is a claim about where two models might disagree; this block turns
it into bare-metal RISC-V that actually reaches the seam and terminates.

The part that matters is the validation gate. Generated assembly fails in ways
that are easy to mistake for results: it does not assemble, or it assembles and
never terminates, or it terminates immediately having executed nothing
interesting. A program that runs zero instructions produces a clean comparison,
and a loop that counts clean comparisons as evidence of correctness will happily
report that a broken generator found no bugs. So every program is assembled,
executed on the oracle under an instruction budget, and required to retire a
minimum number of instructions before it is allowed into the suite.

Category templates are real, working programs rather than sketches. They are the
offline baseline the model's output is measured against, so they have to clear
the same gate.
"""
